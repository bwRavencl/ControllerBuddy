	/// Binds a global, like the inline `wl_registry_bind` function of
	/// `wayland-client-protocol.h`.
	///
	/// @param registry the `wl_registry` proxy
	/// @param name the numeric name of the global
	/// @param iface the interface table of the global
	/// @param version the interface version to bind
	/// @return the bound proxy
	/// @throws IllegalStateException if the proxy could not be created
	public static MemorySegment bind(final MemorySegment registry, final int name, final MemorySegment iface,
			final int version) {
		final var interfaceName = wl_interface.getName(iface.reinterpret(wl_interface.LAYOUT.byteSize()));
		final var result = request(registry, WL_REGISTRY_BIND, iface, version, 0, M_IPIP, name, interfaceName, version,
				MemorySegment.NULL);
		if (isNull(result)) {
			throw new IllegalStateException("wl_registry.bind failed");
		}

		return result;
	}

	/// Sends a request that creates a new object; the object inherits the version
	/// and the event queue of the proxy.
	///
	/// @param proxy the proxy to send the request on
	/// @param opcode the request opcode
	/// @param iface the interface table of the new object
	/// @param marshalMethodHandle the marshal handle matching the arguments
	/// @param args the arguments, starting with a `NULL` placeholder for the new_id
	/// @return the new proxy
	/// @throws IllegalStateException if the proxy could not be created
	public static MemorySegment create(final MemorySegment proxy, final int opcode, final MemorySegment iface,
			final MethodHandle marshalMethodHandle, final Object... args) {
		final var result = request(proxy, opcode, iface, wl_proxy_get_version(proxy), 0, marshalMethodHandle, args);
		if (isNull(result)) {
			throw new IllegalStateException("wl_proxy_marshal_flags returned NULL for opcode " + opcode);
		}

		return result;
	}

	/// Fills an interface table, like the `wl_interface` definitions generated by
	/// `wayland-scanner private-code`.
	///
	/// @param iface the table to fill
	/// @param name the interface name
	/// @param version the interface version
	/// @param requests the requests
	/// @param events the events
	private static void defineInterface(final MemorySegment iface, final String name,
			@SuppressWarnings("SameParameterValue") final int version, final List<Message> requests,
			final List<Message> events) {
		wl_interface.setName(iface, Arena.global().allocateFrom(name));
		wl_interface.setVersion(iface, version);
		wl_interface.setMethod_count(iface, requests.size());
		wl_interface.setMethods(iface, messages(requests));
		wl_interface.setEvent_count(iface, events.size());
		wl_interface.setEvents(iface, messages(events));
	}

	/// Sends a destructor request and then destroys the proxy.
	///
	/// @param proxy the proxy to destroy
	/// @param opcode the opcode of the destructor request
	public static void destroy(final MemorySegment proxy, final int opcode) {
		request(proxy, opcode, MemorySegment.NULL, wl_proxy_get_version(proxy), WL_MARSHAL_FLAG_DESTROY, M_P,
				MemorySegment.NULL);
	}

	/// Returns whether a pointer is `NULL`.
	///
	/// @param segment the pointer
	/// @return `true` if the address is 0
	public static boolean isNull(final MemorySegment segment) {
		return segment.address() == 0L;
	}

	/// Builds a listener table such as `struct zwlr_layer_surface_v1_listener`.
	///
	/// @param arena the arena that owns the table
	/// @param functions the function pointers in event order
	/// @return the table
	public static MemorySegment listener(final Arena arena, final MemorySegment... functions) {
		final var table = arena.allocate(ValueLayout.ADDRESS, functions.length);
		for (var i = 0; i < functions.length; i++) {
			table.setAtIndex(ValueLayout.ADDRESS, i, functions[i]);
		}

		return table;
	}

	/// Creates a downcall handle for `wl_proxy_marshal_flags` with the given
	/// variadic arguments.
	///
	/// @param wlProxyMarshalFlags the address of `wl_proxy_marshal_flags`
	/// @param variadic the layouts of the variadic arguments
	/// @return the downcall handle
	private static MethodHandle marshalMethodHandle(final MemorySegment wlProxyMarshalFlags,
			final MemoryLayout... variadic) {
		final var layouts = new ArrayList<MemoryLayout>(List.of(ValueLayout.ADDRESS, ValueLayout.JAVA_INT,
				ValueLayout.ADDRESS, ValueLayout.JAVA_INT, ValueLayout.JAVA_INT));
		layouts.addAll(List.of(variadic));

		return LINKER
				.downcallHandle(wlProxyMarshalFlags,
						FunctionDescriptor.of(ValueLayout.ADDRESS, layouts.toArray(MemoryLayout[]::new)),
						Linker.Option.firstVariadicArg(5), Linker.Option.critical(false))
				.asSpreader(Object[].class, variadic.length);
	}

