	///
	/// @param name the message name
	/// @param signature the wire signature
	/// @param types the interface tables of the leading object arguments
	/// @return the message description
	/// @throws IllegalArgumentException if there are more types than arguments
	private static Message message(final String name, final String signature, final MemorySegment... types) {
		final var argCount = (int) signature.chars().filter(Character::isLetter).count();
		if (types.length > argCount) {
			throw new IllegalArgumentException("Too many types for " + name);
		}

		final var padded = Arrays.copyOf(types, argCount);
		for (var i = types.length; i < argCount; i++) {
			padded[i] = MemorySegment.NULL;
		}

		return new Message(name, signature, padded);
	}

	/// Builds a native `wl_message` array.
	///
	/// @param messages the message descriptions
	/// @return the array, or `NULL` if there are no messages
	private static MemorySegment messages(final List<Message> messages) {
		if (messages.isEmpty()) {
			return MemorySegment.NULL;
		}

		final var arena = Arena.global();
		final var table = arena.allocate(wl_message.LAYOUT, messages.size());
		for (var i = 0; i < messages.size(); i++) {
			final var message = messages.get(i);
			final var entry = table.asSlice(i * wl_message.LAYOUT.byteSize(), wl_message.LAYOUT);
			final var types = arena.allocate(ValueLayout.ADDRESS, Math.max(1, message.types().length));
			for (var j = 0; j < message.types().length; j++) {
				types.setAtIndex(ValueLayout.ADDRESS, j, message.types()[j]);
			}

			wl_message.setName(entry, arena.allocateFrom(message.name()));
			wl_message.setSignature(entry, arena.allocateFrom(message.signature()));
			wl_message.setTypes(entry, types);
		}

		return table;
	}

	/// Creates an upcall stub that does nothing, for events that are not needed.
	///
	/// @param descriptor the native signature
	/// @param arena the arena that owns the stub
	/// @return the function pointer
	public static MemorySegment noop(final FunctionDescriptor descriptor, final Arena arena) {
		return Linker.nativeLinker().upcallStub(MethodHandles.empty(descriptor.toMethodType()), descriptor, arena);
	}

	/// Sends a request through `wl_proxy_marshal_flags`.
	///
	/// Requests without arguments get an extra `NULL` as dummy argument;
	/// `libwayland-client` only reads as many variadic arguments as the request
	/// signature declares.
	///
	/// @param proxy the proxy to send the request on
	/// @param opcode the request opcode
	/// @param newInterface the interface table of the object created by the
	/// request, or `NULL`
	/// @param version the version of the created object
	/// @param flags `0` or [#WL_MARSHAL_FLAG_DESTROY]
	/// @param marshalMethodHandle the marshal handle matching the variadic
	/// arguments
	/// @param args the variadic arguments
	/// @return the created proxy, or `NULL`
	static MemorySegment request(final MemorySegment proxy, final int opcode, final MemorySegment newInterface,
			final int version, final int flags, final MethodHandle marshalMethodHandle, final Object... args) {
		try {
			return (MemorySegment) marshalMethodHandle.invokeExact(proxy, opcode, newInterface, version, flags, args);
		} catch (final Throwable t) {
			throw new RuntimeException(t);
		}
	}

	/// Sends a request that does not create an object.
	///
	/// @param proxy the proxy to send the request on
	/// @param opcode the request opcode
	/// @param marshalMethodHandle the marshal handle matching the arguments
	/// @param args the arguments
	public static void send(final MemorySegment proxy, final int opcode, final MethodHandle marshalMethodHandle,
			final Object... args) {
		request(proxy, opcode, MemorySegment.NULL, wl_proxy_get_version(proxy), 0, marshalMethodHandle, args);
	}

	/// Creates an upcall stub for an instance method.
	///
	/// The method must take exactly the parameters of the descriptor
	/// (`MemorySegment` for pointers, `int` for integers) and must not throw: an
	/// exception escaping an upcall terminates the JVM.
	///
	/// @param lookup a lookup with access to the method
	/// @param target the receiver
	/// @param method the method name
	/// @param descriptor the native signature
	/// @param arena the arena that owns the stub
	/// @return the function pointer
	/// @throws IllegalStateException if the method does not exist
	public static MemorySegment stub(final MethodHandles.Lookup lookup, final Object target, final String method,
			final FunctionDescriptor descriptor, final Arena arena) {
		try {
			final var handle = lookup.findVirtual(target.getClass(), method, descriptor.toMethodType()).bindTo(target);
			return Linker.nativeLinker().upcallStub(handle, descriptor, arena);
		} catch (final ReflectiveOperationException e) {
			throw new IllegalStateException("Upcall method not found: " + method, e);
		}
	}

