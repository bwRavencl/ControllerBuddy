/// Provides Java bindings to the `libwayland-client` native library.
///
/// Uses the Foreign Function and Memory API to expose the display, event queue
/// and proxy functions of `libwayland-client`, the interface tables it exports,
/// and the interface tables of the `wlr-layer-shell-unstable-v1` protocol that
/// `wayland-scanner` would otherwise generate.
///
/// Requests are sent the same way code generated by `wayland-scanner` sends
/// them: through the variadic function `wl_proxy_marshal_flags`. Every
/// combination of variadic argument types that is used has its own downcall
/// handle (the `M_*` constants), which is passed to [#send], [#create] and
/// [#request].
///
/// Listener tables for events are built from upcall stubs with [#stub],
/// [#noop] and [#listener]. Every event handler receives `(void *data, struct
/// wl_proxy *proxy, ...)`; the names of the `V_*` descriptor constants encode
/// the parameters: `P` for a pointer and `I` for a 32-bit integer, which also
/// covers `uint` and `wl_fixed_t`.
