		/// Field name for the events array.
		private static final String EVENTS_NAME = "events";

		/// Field name for the number of events.
		private static final String EVENT_COUNT_NAME = "event_count";

		/// Field name for the requests array.
		private static final String METHODS_NAME = "methods";

		/// Field name for the number of requests.
		private static final String METHOD_COUNT_NAME = "method_count";

		/// Field name for the interface name.
		private static final String NAME_NAME = "name";

		/// Field name for the interface version.
		private static final String VERSION_NAME = "version";

		/// Memory layout of the Wayland `wl_interface` struct.
		private static final GroupLayout LAYOUT = MemoryLayout.structLayout(ValueLayout.ADDRESS.withName(NAME_NAME),
				ValueLayout.JAVA_INT.withName(VERSION_NAME), ValueLayout.JAVA_INT.withName(METHOD_COUNT_NAME),
				ValueLayout.ADDRESS.withName(METHODS_NAME), ValueLayout.JAVA_INT.withName(EVENT_COUNT_NAME),
				MemoryLayout.paddingLayout(4), ValueLayout.ADDRESS.withName(EVENTS_NAME));

